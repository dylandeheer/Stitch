unset STITCH_BOUNDED_MESH_TASK_LOOKUP STITCH_MESH_BASELINE_FILE
unset STITCH_ORDERED_FIFO_MACRO STITCH_ORDERED_FIFO_MODE_FILE
unset STITCH_DRAW_CPU_FILE STITCH_JIT_WARMUP STITCH_JIT_RUN_FRAME EDEN_NX2_NUP_STAND_INS
unset EDEN_NX2_FAST_DRAW_VERIFY EDEN_NX2_TEXTURE_MEMO_VERIFY
unset EDEN_NX2_FRAME_DUMP EDEN_NX2_FRAME_DUMP_AT EDEN_NX2_FRAME_DUMP_SAMPLED
