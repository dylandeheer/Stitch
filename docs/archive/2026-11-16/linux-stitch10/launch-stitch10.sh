if [ -f "$base/stitch10-jit-run-frame" ]; then
    export STITCH_JIT_RUN_FRAME=1
fi
exec >>"$base/diagnostics/launcher.log" 2>&1
printf '\nStitch 10 launch: %s\n' "$(date --iso-8601=seconds)"
exec "$base/Stitch-OoT-AMD-10-x86_64.AppImage" "$@"
