export XDG_DATA_HOME="$base/profile10/data"
export XDG_CACHE_HOME="$base/profile10/cache"
export EDEN_NX2_DEBUG_SERVER=127.0.0.1:6545
export EDEN_NX2_DEBUG_DIR="$base/diagnostics"
export EDEN_NX2_TC_LOG=1
export EDEN_NX2_MESH_EMPTY_BASELINE_FILE="$base/diagnostics/stitch10-mesh-empty-baseline"
export EDEN_NX2_TC_GC_BASELINE_FILE="$base/diagnostics/stitch10-texture-gc-baseline"
export EDEN_NX2_JOIN_UPLOAD_BASELINE_FILE="$base/diagnostics/stitch10-join-upload-baseline"
unset STITCH_WRITER_FRONTIER STITCH_WRITER_VERIFY STITCH_WRITER_FRONTIER_FILE
unset EDEN_NX2_GPU_PROFILE EDEN_DKB_FRAME_TRACE EDEN_NX2_MESH_PERF EDEN_NX2_MESH_PERF_FILE
unset STITCH_READBACK_TRACE EDEN_NX2_UPLOAD_TIMING
unset EDEN_NX2_SKIP_UNUSED_XFB_BARRIERS EDEN_NX2_SPARSE_SAMPLE_COPIES
unset STITCH_QUERY_BASELINE_FILE STITCH_IMAGE_POOL_BASELINE_FILE
unset STITCH_BOUNDED_READ_BATCH_BASELINE_FILE STITCH_ATLAS_SNAPSHOT_BASELINE_FILE
